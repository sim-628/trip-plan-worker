import { build } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";
const result = await build({
  entryPoints: ["web/app.ts"],
  bundle: true,
  write: false,
  minify: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
});
const html = await readFile("web/index.html", "utf8"),
  css = await readFile("web/styles.css", "utf8"),
  js = result.outputFiles[0].text;
await mkdir("src/web", { recursive: true });
await writeFile(
  "src/web/assets.generated.ts",
  `// Generated by scripts/build-web.mjs.\nexport const html=${JSON.stringify(html)};\nexport const css=${JSON.stringify(css)};\nexport const js=${JSON.stringify(js)};\n`,
);
console.log("Built the browser test interface.");
